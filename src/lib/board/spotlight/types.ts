import type { BoardCategory } from "@/lib/board/config";
import type { NewListingInput } from "@/lib/board/types";

/** "hour" = a Spotlight hour on the homepage. "day" = a Sponsor day on the free tools. */
export type UnitKind = "hour" | "day";

/** The public face of whoever booked a placement. `url` is null when it did not pass the link check. */
export interface PlacementListing {
  /** Stable key (hostname, or host/first-path-segment). */
  domain: string;
  name: string;
  /** Normalised https/http destination, already checked with checkListingUrl, or null if there is no safe link. */
  url: string | null;
  category: BoardCategory | null;
}

/** One booked hour (start = epoch ms of the hour, UTC) or one booked day (start = epoch ms of 00:00 UTC). */
export interface Booking {
  id: string;
  start: number;
  listing: PlacementListing;
  headline: string;
  /** True for sample bookings generated by the demo adapter. */
  sample?: boolean;
}

export interface Calendar {
  kind: UnitKind;
  rangeStart: number;
  rangeEnd: number;
  bookings: Booking[];
  generatedAt: number;
}

export interface CurrentPlacement {
  kind: UnitKind;
  /** Start of the current hour or day (UTC). */
  start: number;
  /** Who holds the current hour or day, or null if it is open. */
  booking: Booking | null;
  /** Cheapest price among the units that can still be booked, or null if everything is taken. */
  fromCents: number | null;
}

export type PurchaseErrorCode =
  | "empty"
  | "invalid"
  | "duplicate"
  | "too_many"
  | "past"
  | "beyond"
  | "conflict"
  | "terms"
  | "listing"
  | "headline"
  | "unknown_listing"
  | "rate_limited"
  | "network"
  | "server";

export type OrderStatus = "pending" | "paid" | "failed" | "expired";

export interface Order {
  orderId: string;
  kind: UnitKind;
  status: OrderStatus;
  /** The bookings this order created or is holding. Empty for failed and expired orders. */
  bookings: Booking[];
  subtotalCents: number;
  discountCents: number;
  totalCents: number;
}

interface PurchaseBase {
  /** An existing listing key, or a new listing (its tagline is the headline). Exactly one of the two. */
  domain?: string;
  listing?: NewListingInput;
  headline: string;
  acceptedTerms: boolean;
  /** Reused on retry so a double click or a retry never books or charges twice. */
  idempotencyKey?: string;
  /** Live mode only: where the hosted payment page sends the buyer back to (the page appends ?order=ID). */
  returnUrl?: string;
}

export interface PurchaseSlotsRequest extends PurchaseBase {
  /** Hour starts, epoch ms. */
  slots: number[];
}

export interface PurchaseDaysRequest extends PurchaseBase {
  /** Day starts (00:00 UTC), epoch ms. */
  days: number[];
}

export type PurchaseResult =
  | { ok: true; orderId: string; order: Order | null; checkoutUrl?: string }
  | { ok: false; error: string; code: PurchaseErrorCode; conflicts?: number[] };

export type OrderResult = { ok: true; order: Order } | { ok: false; error: string };

/** The one interface both the demo adapter and the live HTTP client implement. */
export interface SpotlightApi {
  getSpotlight(rangeStart: number, rangeEnd: number): Promise<Calendar>;
  getCurrentSpotlight(): Promise<CurrentPlacement>;
  purchaseSlots(req: PurchaseSlotsRequest): Promise<PurchaseResult>;
  getSponsorDays(rangeStart?: number, rangeEnd?: number): Promise<Calendar>;
  getCurrentSponsor(): Promise<CurrentPlacement>;
  purchaseSponsorDays(req: PurchaseDaysRequest): Promise<PurchaseResult>;
  /** Look up an order, used when the buyer returns from a hosted payment page. */
  getOrder(orderId: string): Promise<OrderResult>;
  subscribe(cb: () => void): () => void;
}
